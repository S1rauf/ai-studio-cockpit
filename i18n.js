    setLang: function(l) {
        this.lang = l === 'ru' ? 'ru' : 'en';
        localStorage.setItem('cockpit_lang', this.lang);
    },

    t: function(key, vars = {}) {
        const table = this.dict[this.lang] || this.dict.en;
        let str = table[key] || this.dict.en[key] || key;
        Object.entries(vars).forEach(([k, v]) => {
            str = str.replaceAll(`{${k}}`, () => String(v));
        });
        return str;
    },

    getHelpSections: function() {
        return this.helpSections[this.lang] || this.helpSections.en;
    }
